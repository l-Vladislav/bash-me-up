export const GLYPH_HEIGHT = 5;

/** Characters the font can draw; anything else is drawn as `?`. */
export const supported = (char: string): boolean => char.toUpperCase() in GLYPHS;

export const renderBanner = (text: string): string[] => {
  const glyphs = [...text.toUpperCase()].map((char) => GLYPHS[char] ?? GLYPHS['?'] ?? []);
  return Array.from({ length: GLYPH_HEIGHT }, (_, row) =>
    glyphs
      .map((glyph) => glyph[row] ?? '')
      .join(' ')
      .trimEnd(),
  );
};
